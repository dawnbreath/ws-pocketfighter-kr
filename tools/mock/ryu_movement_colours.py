RECIPES = {"RYU": {"poses": tuple(REGIONS)}}


def author(character: str, source: np.ndarray) -> np.ndarray:
    key = hashlib.md5(source.tobytes() + bytes(source.shape)).hexdigest()
    if character != "RYU" or key not in REGIONS:
        raise ValueError("unsupported Ryu movement drawing")
    return paint_materials(source, REGIONS[key])
