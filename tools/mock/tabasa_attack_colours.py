RECIPES = {"TABASA": {"poses": tuple(REGIONS)}}


def author(character: str, source: np.ndarray) -> np.ndarray:
    key = hashlib.md5(source.tobytes() + bytes(source.shape)).hexdigest()
    if character != "TABASA" or key not in REGIONS:
        raise ValueError("unsupported Tabasa attack drawing")
    out = source.copy()
    for material, points in REGIONS[key]:
        mask = selection(source.shape, points) & (source != 0)
        out[mask] = np.asarray(RAMPS[material], dtype=np.uint8)[source[mask]]
    return out
