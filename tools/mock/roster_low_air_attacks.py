def author(character: str, source: np.ndarray) -> np.ndarray:
    key = hashlib.md5(source.tobytes() + bytes(source.shape)).hexdigest()
    if key not in REGIONS.get(character, {}):
        raise ValueError("unsupported crouching or airborne attack drawing")
    result = source.astype(np.int8).copy()
    for material, points in REGIONS[character][key]:
        mask = selection(source.shape, points) & (source > 0)
        result[mask] = np.take(RAMPS[material], source[mask])
    return result


def for_context(context: int) -> SimpleNamespace:
    selectors = {"MORRIGAN": 2, "TABASA": 3}
    if context not in (0, 2, 3):
        raise ValueError("no low attack drawings for this selector")
    recipes = {
        name: {"poses": tuple(rows)}
        for name, rows in REGIONS.items()
        if selectors.get(name, 0) == context
    }
    return SimpleNamespace(__file__=__file__, author=author, RECIPES=recipes)
