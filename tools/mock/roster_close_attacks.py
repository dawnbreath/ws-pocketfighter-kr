def author(character: str, source: np.ndarray) -> np.ndarray:
    key = hashlib.md5(source.tobytes() + bytes(source.shape)).hexdigest()
    if key not in REGIONS.get(character, {}):
        raise ValueError("unsupported close attack drawing")
    return paint_materials(source, REGIONS[character][key])


def for_context(context: int) -> SimpleNamespace:
    recipes = {
        who: {"poses": tuple(drawings)}
        for who, drawings in REGIONS.items()
        if ACTOR_CONTEXTS.get(who, 0) == context
    }
    if not recipes:
        raise ValueError("no close attack drawings for this context")
    return SimpleNamespace(__file__=__file__, author=author, RECIPES=recipes)
