def author(source: np.ndarray) -> np.ndarray:
    key = hashlib.md5(source.tobytes() + bytes(source.shape)).hexdigest()
    if key not in POSES:
        raise ValueError("unsupported basic attack drawing")
    n = POSES.index(key)
    out = source.astype(np.int8).copy()
    # Clothing below the hands; preserve the exposed trailing hand of kick prep.
    lower = (np.indices(source.shape)[0] >= [29, 32, 31, 24, 24, 25][n]) & (source > 0)
    out[lower] += 8
    for group in [2, 1, 3, 4]:
        for points in REGIONS[n].get(group, []):
            mask = Image.new("1", (source.shape[1], source.shape[0]))
            ImageDraw.Draw(mask).polygon(points, fill=1)
            selected = np.array(mask, dtype=bool) & (source > 0)
            out[selected] = 4 if group == 4 else group * 4 + source[selected]
    for x, y in STUDS[n]:
        if source[y, x]:
            out[y, x] = 13
    # The same two-pixel source tile appears at the kicking boot's dark edge
    # and the trouser contour. Keep one common dark outline, not conflicting
    # position-dependent colours. Punch also shares one contour with T30.
    for x, y in {2: [(15, 32), (16, 32)], 5: [(7, 28)]}.get(n, []):
        out[y, x] = 3
    return out
