# Preserve these already-coloured shared raw-tile pixels byte for byte.
# Tiny edge fragments recur in previous action drawings; no table overwrite.
SHARED_PIXELS = {
    PRONE: [(2, 14, 3)],
    ROLL_B: [(1, 5, 7), (0, 6, 3), (1, 6, 6), (0, 7, 3)],
}


def author(source: np.ndarray) -> np.ndarray:
    key = hashlib.md5(source.tobytes() + bytes(source.shape)).hexdigest()
    if key not in POSES:
        raise ValueError("unsupported knockdown/recovery drawing")
    out = source.astype(np.int8).copy()
    for group in (2, 1, 3, 4):
        for points in REGIONS[key].get(group, []):
            mask = Image.new("1", (source.shape[1], source.shape[0]))
            ImageDraw.Draw(mask).polygon(points, fill=1)
            selected = np.array(mask, dtype=bool) & (source > 0)
            out[selected] = 4 if group == 4 else group * 4 + source[selected]
    for x, y in STUDS[key]:
        if source[y, x]:
            out[y, x] = 13
    for x, y, value in SHARED_PIXELS.get(key, []):
        out[y, x] = value
    return out
