def lerp(a,b,t): return tuple(int(a[i]+(b[i]-a[i])*t) for i in range(3))
def ramp(d,l,mid=None):
    if mid is None: return [lerp(d,l,k/4) for k in range(5)]
    return [d,lerp(d,mid,.6),mid,lerp(mid,l,.5),l]
