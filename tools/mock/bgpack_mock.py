    SL1=[(238,90,170),(250,210,50),(70,140,250)]; SL2=[(70,140,250),(250,210,50),(238,90,170)]
    P1=[(9,37),(40,67),(72,102)]; P2=[(122,150),(152,180),(185,215)]
    for y in range(144):
        for x in range(224):
            c=px[x,y]
            if c in ((85,221,221),(17,102,136)):
                light=(c==(85,221,221))
                if y<30:
                    if 88<=x<=136: op[x,y]=(130,120,255) if light else (40,30,120)
                    else: op[x,y]=(250,235,40) if light else (110,60,130)
                elif y>=112:
                    for sl,(a,b) in enumerate(P1+P2):
                        if a<=x<=b+1:
                            col=(SL1+SL2)[sl]; op[x,y]=col if light else tuple(int(v*0.45) for v in col); break
    return out
